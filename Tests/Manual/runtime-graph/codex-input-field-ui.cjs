const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const {chromium}=require(process.env.AGENTREINS_PLAYWRIGHT||'playwright');
const root=process.env.AGENTREINS_CODEX_INPUT_FIELD_DIR;if(!root)throw Error('Actual Codex field data required');
(async()=>{
 const payload=JSON.parse(fs.readFileSync(path.join(root,'actual-codex-input-payload.json'),'utf8'));
 const latest=payload.tasks.find(t=>t.originalRequest==='修复 这个问题');
 const earlier=payload.tasks.find(t=>t.originalRequest==='继续完成');
 assert.equal(earlier.userInputs.length,2);assert.equal(latest.userInputs.length,1);
 const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1680,height:1180}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve(__dirname,'../../../Sources/AgentReins/Resources/RealtimeWorkspace/index.html'));
 await page.evaluate(p=>window.agentreinsReceive(p),payload);
 assert((await page.locator('h1').textContent()).includes('修复 这个问题'));
 await page.locator('[data-flow-node=user]').click();
 assert((await page.locator('#detail-code').textContent()).includes('修复 这个问题'));
 assert(!(await page.locator('#detail-code').textContent()).includes('external_codex_apps_open_page'));
 await page.locator('[data-task]').filter({hasText:'codex 的用户输入 一直采集失败'}).click();
 assert((await page.locator('h1').textContent()).includes('codex 的用户输入 一直采集失败'));
 assert((await page.locator('.request').first().textContent()).includes('继续完成'));
 assert((await page.locator('.latest-input').textContent()).includes('codex 的用户输入 一直采集失败'));
 await page.locator('[data-flow-node=user]').click();
 let detail=await page.locator('#detail-code').textContent();
 assert(detail.includes('继续完成')&&detail.includes('codex 的用户输入 一直采集失败'));
 assert.equal(await page.locator('#detail-code h3').count(),2);
 assert.equal(await page.locator('[data-flow-node]').count(),16);
 await page.screenshot({path:path.join(root,'input-timeline.png'),fullPage:true});
 await page.locator('details.canvas-tools').evaluate(el=>{el.open=true});await page.locator('[data-graph-mode=spider]').click();assert.equal(await page.locator('#detail-code').textContent(),detail);
 await page.screenshot({path:path.join(root,'input-spider.png'),fullPage:true});
 assert.deepEqual(errors,[]);console.log(JSON.stringify({passed:true,actualRawInputs:3,displayedInputs:3,sourceEvidenceIDs:6,steeringVisible:true,pageContextExcluded:true,bothModes:true}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
